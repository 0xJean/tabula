CREATE ROLE tabula_reader_writer LOGIN PASSWORD 'local_demo_app';
CREATE TABLE public.notes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id text NOT NULL,
    body text NOT NULL,
    UNIQUE (tenant_id, body)
);
ALTER TABLE public.notes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.notes FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_rows ON public.notes TO tabula_reader_writer
    USING (tenant_id = current_setting('demo.tenant', true))
    WITH CHECK (tenant_id = current_setting('demo.tenant', true));
GRANT SELECT, INSERT, UPDATE ON public.notes TO tabula_reader_writer;
GRANT USAGE ON SEQUENCE public.notes_id_seq TO tabula_reader_writer;
