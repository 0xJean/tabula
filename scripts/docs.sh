#!/usr/bin/env bash
# Regenerate the public reference from this checkout, or check the committed copy.
set -euo pipefail
cd "$(dirname "$0")/.."
mode=${1:---check}
IFS= read -r title < docs/INTEGRATION.md
series=${title##* }
if [[ $title != '# '* || ! $series =~ ^v[0-9]+\.[0-9]+$ ]]; then
  echo 'The integration guide title must identify its vMAJOR.MINOR series.' >&2
  exit 1
fi
case "$mode" in
  --series) echo "$series"; exit 0 ;;
  --check|--write) ;;
  *) echo "Usage: scripts/docs.sh [--check | --write | --series]" >&2; exit 2 ;;
esac

scratch=$(mktemp -d)
trap 'rm -rf "$scratch"' EXIT
# Product libraries live in the core, pgxdriver and oteltabula modules. Examples are commands.
go list -f '{{if ne .Name "main"}}{{.ImportPath}}{{end}}' ./... ./pgxdriver/... ./oteltabula/... |
  awk '$0 !~ /\/internal(\/|$)/ && NF' | LC_ALL=C sort > "$scratch/packages"
go build -o "$scratch/tabula" ./cmd/tabula
"$scratch/tabula" --help > "$scratch/usage"
awk '$1 == "tabula" {print $2}' "$scratch/usage" > "$scratch/commands"
test -s "$scratch/packages"
test -s "$scratch/commands"

if [[ "$mode" == --check ]]; then
  # Check both directions so deleting a command also retires its guide link.
  {
    awk -F/ '{print $NF}' "$scratch/packages"
    sed 's/^/tabula-/' "$scratch/commands"
  } | LC_ALL=C sort > "$scratch/expected"
  grep -Eo '\(REFERENCE\.md#[^)]*\)' docs/INTEGRATION.md |
    sed -e 's/^(REFERENCE\.md#//' -e 's/)$//' -e '/^cli$/d' |
    LC_ALL=C sort -u > "$scratch/linked"
  if ! diff -u "$scratch/expected" "$scratch/linked"; then
    echo 'Update the public package and command links in docs/INTEGRATION.md.' >&2
    exit 1
  fi
fi

{
  cat <<'HEADER'
<!-- Generated by scripts/docs.sh. Edit the Go declarations, GoDoc or command help and regenerate. -->
# Go API and CLI reference

This reference belongs to the same revision as the code. Start with the [integration guide](INTEGRATION.md) to find the operation you need.

HEADER
  while IFS= read -r pkg; do
    name=${pkg##*/}
    printf -- '- [%s](#%s)\n' "$name" "$name"
  done < "$scratch/packages"
  printf -- '- [CLI commands and flags](#cli)\n'
  while IFS= read -r pkg; do
    printf '\n## %s\n\n```text\n' "${pkg##*/}"
    go doc -all "$pkg"
    printf '```\n'
  done < "$scratch/packages"
  printf '\n## CLI\n\n```text\n'
  cat "$scratch/usage"
  printf '```\n'
  while IFS= read -r cmd; do
    printf '\n### tabula %s\n\n```text\n' "$cmd"
    "$scratch/tabula" "$cmd" -h 2>&1 | expand -t 8
    printf '```\n'
  done < "$scratch/commands"
} > "$scratch/reference"

if [[ "$mode" == --write ]]; then
  cp "$scratch/reference" docs/REFERENCE.md
elif ! diff -u docs/REFERENCE.md "$scratch/reference"; then
  echo 'Public reference is stale. Run scripts/docs.sh --write and review the diff.' >&2
  exit 1
fi
